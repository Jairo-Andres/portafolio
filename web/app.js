const STORE_KEY = "ja-lang";
const original = new Map();

function readLang() {
  const param = new URLSearchParams(location.search).get("lang");
  if (param === "en" || param === "es") return param;
  try { return localStorage.getItem(STORE_KEY) === "en" ? "en" : "es"; } catch { return "es"; }
}

function remember(el, key, value) {
  if (!original.has(el)) original.set(el, {});
  const saved = original.get(el);
  if (!(key in saved)) saved[key] = value;
  return saved[key];
}

function apply(lang) {
  const en = lang === "en";
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const es = remember(el, "text", el.textContent);
    el.textContent = en ? EN[el.dataset.i18n] ?? es : es;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const es = remember(el, "html", el.innerHTML);
    el.innerHTML = en ? EN[el.dataset.i18nHtml] ?? es : es;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const es = remember(el, "aria", el.getAttribute("aria-label"));
    el.setAttribute("aria-label", en ? EN[el.dataset.i18nAria] ?? es : es);
  });
  // Los proyectos también aceptan ?lang=en: el enlace conserva el idioma elegido.
  document.querySelectorAll("[data-lang-link]").forEach((el) => {
    const url = new URL(el.getAttribute("href"), location.href);
    if (en) url.searchParams.set("lang", "en"); else url.searchParams.delete("lang");
    el.setAttribute("href", url.origin === location.origin ? url.pathname + url.search : url.href);
  });

  const toggle = document.getElementById("lang-toggle");
  toggle.textContent = en ? "ES" : "EN";
  toggle.lang = en ? "es" : "en";
  toggle.setAttribute("aria-label", en ? "Leer en español" : "Read in English");
}

let lang = readLang();
apply(lang);

document.getElementById("lang-toggle").addEventListener("click", () => {
  lang = lang === "en" ? "es" : "en";
  try { localStorage.setItem(STORE_KEY, lang); } catch { /* sin almacenamiento: solo esta visita */ }
  const url = new URL(location.href);
  if (lang === "en") url.searchParams.set("lang", "en"); else url.searchParams.delete("lang");
  history.replaceState(null, "", url);
  apply(lang);
});

// Tren del mapa de líneas: va de estación en estación, se detiene en cada una y la marca
// mientras está parado. Con "reducir movimiento" no se crea.
const reduceMotion = matchMedia("(prefers-reduced-motion: reduce)");
const horizontal = matchMedia("(min-width: 48rem)");
const TRAVEL = 1800; // ms entre estaciones (igual que la transición de .train)
const STOP = 1600;   // ms parado en cada estación

function stationPoint(li) {
  // Centro del círculo de la estación, relativo a la lista (ver .line li::before en styles.css)
  return horizontal.matches ? [li.offsetLeft + 8, 12] : [12, li.offsetTop + 10];
}

function runLine(line, delay) {
  const stops = [...line.querySelectorAll("li")];
  const train = document.createElement("span");
  train.className = "train";
  train.setAttribute("aria-hidden", "true");
  line.append(train);

  let i = 0;
  let dir = 1;
  const place = (instant) => {
    const [x, y] = stationPoint(stops[i]);
    if (instant) train.style.transition = "none";
    train.style.transform = `translate(${x}px, ${y}px)`;
    if (instant) { train.offsetWidth; train.style.transition = ""; }
  };
  place(true);

  const step = () => {
    stops[i].classList.add("is-stop");
    setTimeout(() => {
      stops[i].classList.remove("is-stop");
      if (i + dir < 0 || i + dir >= stops.length) dir = -dir;
      i += dir;
      place(false);
      setTimeout(step, TRAVEL);
    }, STOP);
  };
  setTimeout(step, delay);
  horizontal.addEventListener("change", () => place(true));
  addEventListener("resize", () => place(true));
}

if (!reduceMotion.matches) {
  document.querySelectorAll(".map .line").forEach((line, n) => runLine(line, n * 900));
}

// Cabecera: marca la sección que se está viendo (Inicio, Proyectos o Juegos).
const navLinks = [...document.querySelectorAll(".tabs a[data-nav]")];
const sections = [
  ["juegos", document.getElementById("juegos")],
  ["rutas", document.getElementById("rutas")],
];
function markNav() {
  const y = innerHeight * 0.35;
  const current = sections.find(([, el]) => el && el.getBoundingClientRect().top <= y)?.[0] ?? "inicio";
  navLinks.forEach((a) => {
    if (a.dataset.nav === current) a.setAttribute("aria-current", current === "inicio" ? "page" : "location");
    else a.removeAttribute("aria-current");
  });
}
addEventListener("scroll", markNav, { passive: true });
addEventListener("hashchange", markNav);
markNav();

// Pantallas de los juegos: se inclinan siguiendo el puntero (solo ratón, y nunca con "reducir movimiento").
const finePointer = matchMedia("(hover: hover) and (pointer: fine)");
document.querySelectorAll(".game").forEach((card) => {
  const tilt = card.querySelector(".tilt");
  if (!tilt) return;
  card.addEventListener("pointermove", (e) => {
    if (reduceMotion.matches || !finePointer.matches || e.pointerType !== "mouse") return;
    const r = card.getBoundingClientRect();
    const x = (e.clientX - r.left) / r.width - 0.5;
    const y = (e.clientY - r.top) / r.height - 0.5;
    card.classList.add("is-tracking");
    tilt.style.setProperty("--ry", `${(x * 16).toFixed(2)}deg`);
    tilt.style.setProperty("--rx", `${(-y * 10).toFixed(2)}deg`);
  });
  card.addEventListener("pointerleave", () => {
    card.classList.remove("is-tracking");
    tilt.style.removeProperty("--ry");
    tilt.style.removeProperty("--rx");
  });
});

